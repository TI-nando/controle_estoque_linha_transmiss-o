-- Cadastros ---------------------------------------------------------------
create table canteiro (
    id           bigint generated by default as identity primary key,
    nome         varchar(120) not null,
    local        varchar(160),
    responsavel  varchar(120),
    ativo        boolean      not null default true,
    criado_em    timestamp    not null,
    constraint uk_canteiro_nome unique (nome)
);

create table tipo_torre (
    id      bigint generated by default as identity primary key,
    codigo  varchar(30)  not null,
    nome    varchar(120),
    funcao  varchar(120),
    constraint uk_tipo_torre_codigo unique (codigo)
);

create table componente (
    id              bigint generated by default as identity primary key,
    tipo_torre_id   bigint       not null references tipo_torre (id),
    nome            varchar(120) not null,
    qtd_por_torre   integer      not null check (qtd_por_torre >= 0),
    peso_kg         numeric(12, 3),
    ordem           integer      not null default 0,
    constraint uk_componente_nome unique (tipo_torre_id, nome)
);

-- meta de torres de cada tipo que o canteiro precisa montar
create table canteiro_meta (
    canteiro_id     bigint  not null references canteiro (id),
    tipo_torre_id   bigint  not null references tipo_torre (id),
    quantidade      integer not null check (quantidade >= 0),
    primary key (canteiro_id, tipo_torre_id)
);

-- Transferências (precisam existir antes do razão) -------------------------
create table transferencia (
    id                 bigint generated by default as identity primary key,
    numero             varchar(30)  not null,
    origem_id          bigint       not null references canteiro (id),
    destino_id         bigint       not null references canteiro (id),
    tipo_torre_id      bigint       not null references tipo_torre (id),
    status             varchar(20)  not null,
    observacao         varchar(500),
    romaneio           varchar(80),
    veiculo            varchar(120),
    obs_recebimento    varchar(500),
    divergencia_tratada boolean     not null default false,
    criado_em          timestamp    not null,
    criado_por         varchar(120),
    despachado_em      timestamp,
    despachado_por     varchar(120),
    recebido_em        timestamp,
    recebido_por       varchar(120),
    cancelado_em       timestamp,
    cancelado_por      varchar(120),
    versao             bigint       not null default 0,
    constraint uk_transferencia_numero unique (numero),
    constraint ck_transferencia_canteiros check (origem_id <> destino_id)
);
create index ix_transferencia_status on transferencia (status);
create index ix_transferencia_origem on transferencia (origem_id, tipo_torre_id, status);

create table transferencia_item (
    id                   bigint generated by default as identity primary key,
    transferencia_id     bigint  not null references transferencia (id),
    componente_id        bigint  not null references componente (id),
    quantidade           integer not null check (quantidade > 0),
    quantidade_recebida  integer check (quantidade_recebida >= 0)
);

-- Razão do estoque (append-only) -------------------------------------------
create table movimento (
    id                bigint generated by default as identity primary key,
    natureza          varchar(20)  not null,
    canteiro_id       bigint       not null references canteiro (id),
    tipo_torre_id     bigint       not null references tipo_torre (id),
    data_movimento    date         not null,
    criado_em         timestamp    not null,
    usuario           varchar(120),
    documento         varchar(120),
    observacao        varchar(500),
    numero_torre      varchar(40),
    transferencia_id  bigint references transferencia (id),
    estorno_de_id     bigint references movimento (id),
    -- um lançamento só pode ser estornado uma vez
    constraint uk_movimento_estorno unique (estorno_de_id),
    -- cada transferência gera no máximo um envio e um recebimento
    constraint uk_movimento_transf unique (transferencia_id, natureza)
);
create index ix_movimento_canteiro_tipo on movimento (canteiro_id, tipo_torre_id);
create index ix_movimento_torre on movimento (numero_torre);

create table movimento_item (
    id             bigint generated by default as identity primary key,
    movimento_id   bigint  not null references movimento (id),
    componente_id  bigint  not null references componente (id),
    quantidade     integer not null check (quantidade <> 0)
);
create index ix_movimento_item_mov on movimento_item (movimento_id);
